#!/usr/bin/env node
/**
 * Regenerate `src/theme-presets.ts` from the foundation pack's theme atoms.
 *
 *   node scripts/sync-theme-presets.mjs --from <packs-repo>/foundation/src/appearance
 *   node scripts/sync-theme-presets.mjs --from <dir> --check   # exit 1 when the table drifted
 *
 * WHY A COPY EXISTS AT ALL. An app may carry
 * `appearance.json = { "use": "theme-zinc" }` and nothing else. The runner is
 * a static ES module in the published app: it cannot ask a host which atoms
 * are installed, so without a copy a bare name would resolve to nothing and
 * the app would paint the default indigo. The runner therefore
 * carries the token sets of the foundation presets — data only, regenerated by
 * this script, never edited by hand. The dependency direction stays intact:
 * core reads a snapshot of the pack's values; nothing in core imports the pack.
 *
 * Zero dependencies, like every script that reads pack source.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const argv = process.argv.slice(2)
const flag = (name) => {
  const i = argv.indexOf(name)
  return i === -1 ? null : argv[i + 1] ?? null
}
const from = flag('--from')
if (!from || !existsSync(from)) {
  console.error('usage: sync-theme-presets.mjs --from <foundation/src/appearance> [--check]')
  process.exit(2)
}

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', 'src', 'theme-presets.ts')

const presets = {}
let packVersion = null
try {
  packVersion = JSON.parse(readFileSync(join(from, '..', '..', 'package.json'), 'utf8')).version ?? null
} catch {
  packVersion = null
}
for (const dir of readdirSync(from).sort()) {
  const manifest = join(from, dir, 'manifest.json')
  if (!existsSync(manifest)) continue
  const atom = JSON.parse(readFileSync(manifest, 'utf8'))
  if (atom.kind !== 'ui-appearance' || !atom.theme) continue
  presets[atom.id] = atom.theme
}

const body = `/**
 * GENERATED by scripts/sync-theme-presets.mjs — do not edit by hand.
 * Source: foundation${packVersion ? ` ${packVersion}` : ''} src/appearance (${Object.keys(presets).length} themes).
 *
 * The token sets a bare \`{ "use": "<theme>" }\` resolves to in a published app.
 * See the script for why the runner carries them.
 *
 * @module @pwfabric/runner/theme-presets
 */

export const THEME_PRESETS: Readonly<Record<string, Readonly<Record<string, unknown>>>> = ${JSON.stringify(presets, null, 2)}
`

if (argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : ''
  if (current.replace(/\r\n/g, '\n') !== body) {
    console.error(`theme-presets.ts has drifted from ${from} — rerun without --check`)
    process.exit(1)
  }
  console.log(`theme-presets.ts matches ${from}`)
} else {
  writeFileSync(out, body)
  console.log(`wrote ${out} — ${Object.keys(presets).join(', ')}`)
}
